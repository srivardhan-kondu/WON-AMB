// Postgres persistence (Neon, via node-postgres). Schema mirrors §4 of the software design doc;
// times are stored as (day, minutes-from-IST-midnight) and money in paise.
// The DB is the source of truth — the engine ledger is always rebuilt from it.
//
// `db().prepare(sql).get/all/run(...)` keeps the shape of the old SQLite API but is async. SQL may use
// `?` positional or `@name` named placeholders; both are rewritten to Postgres `$n`.
// `tx(fn)` runs fn in a transaction; every query issued inside it (at any depth) joins that transaction.
// All transactions take one advisory lock, so commits are serialized exactly like the old single-writer
// SQLite setup — a commit always re-verifies against a ledger nobody else is changing (§10).

import { AsyncLocalStorage } from "node:async_hooks";
